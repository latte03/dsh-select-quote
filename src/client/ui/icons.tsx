/** Markup form for plain-DOM call sites; `insertAdjacentHTML('afterbegin', …)`. */
export function iconMarkup(name: IconName, size = 15): string {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="${size}" height="${size}" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${SHAPES[name]}</svg>`
}

export function LucideIcon({
  name,
  size = 15,
  className,
}: {
  name: IconName
  size?: number
  className?: string
}): ReactNode {
  return (
    <svg
      {...SVG_ATTRS}
      className={className}
      width={size}
      height={size}
      dangerouslySetInnerHTML={{ __html: SHAPES[name] }}
    />
  )
}
